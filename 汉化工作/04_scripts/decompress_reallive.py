def header(buf: bytes):
    sig=buf[:4]
    if sig not in (b'KPRL',b'RDRL',b'KPRM',b'RDRM') and sig != b'\xd0\x01\x00\x00':
        raise ValueError(f'unsupported sig {sig!r}')
    compver = struct.unpack_from('<I',buf,4)[0]
    doff=struct.unpack_from('<I',buf,0x20)[0]
    usize=struct.unpack_from('<I',buf,0x24)[0]
    csize=struct.unpack_from('<I',buf,0x28)[0]
    return compver,doff,usize,csize

def decompress_blob(blob: bytes):
    compver,doff,usize,csize=header(blob)
    arr=bytearray(blob)
    for j in range(doff,len(arr)):
        arr[j]^=XOR_MASK[(j-doff)&0xff]
    if csize==0:
        return bytes(arr), (compver,doff,usize,csize)
    src=memoryview(arr)[doff:doff+csize]
    if len(src)<9: raise ValueError('short compressed')
    si=8; flag=src[si]; si+=1; bit=1; out=bytearray()
    while si < len(src) and len(out) < usize:
        if bit==256:
            bit=1
            if si>=len(src): break
            flag=src[si]; si+=1
        if flag & bit:
            if si>=len(src): raise ValueError('literal eof')
            out.append(src[si]); si+=1
        else:
            if si+1>=len(src): raise ValueError('backref eof')
            count=src[si] | (src[si+1]<<8); si+=2
            dist=(count>>4)
            n=(count&0x0f)+2
            pos=len(out)-dist
            if pos<0 or pos>=len(out): raise ValueError(f'corrupt backref pos={pos} out={len(out)}')
            for _ in range(n):
                out.append(out[pos]); pos+=1
        bit <<= 1
    if len(out)!=usize:
        raise ValueError(f'size mismatch got={len(out)} expected={usize}')
    if compver==110002:
        for i in range(257):
            p=256+i
            if p>=len(out): break
            out[p]^=KEY2[i%16]
    rv=bytearray(doff+usize)
    rv[:doff]=arr[:doff]
    rv[doff:]=out
    return bytes(rv),(compver,doff,usize,csize)

